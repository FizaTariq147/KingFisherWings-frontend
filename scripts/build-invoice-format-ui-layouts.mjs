function deepClone(obj) {
  return JSON.parse(JSON.stringify(obj));
}

/** Formats pinned to layout families (KingFisher copies of sample structures). */
const FORMAT_KIND_OVERRIDE = {
  12: 'preprinted',
  23: 'purchase_2',
  24: 'simple_os',
  25: 'simple_india_os',
  26: 'fg_simple_invoice',
  27: 'tanzania',
  28: 'singapore',
  29: 'land',
  30: 'overseas_debit_2',
};

/**
 * No EXTRA duplicate codes — every invoice lives as INVOICE_REPORT_FORMAT_N only.
 * Proforma / Singapore / Land / Overseas debit are Formats 71 / 28 / 29 / 30.
 */
const EXTRA_LAYOUT_SPECS = [];

function scrubDemo(demo) {
  return JSON.parse(
    JSON.stringify(demo || {}).replace(/Fresa/gi, 'KingFisher').replace(/FRESA/g, 'KingFisher'),
  );
}

function toLayoutRow(p, base, kind, fromDistinct = false) {
  return {
    code: p.code,
    formatNumber: p.formatNumber,
    name: String(p.name || '').replace(/Fresa/gi, 'KingFisher'),
    paper: p.paper || base.paper || (kind === 'usa' ? 'Letter' : 'A4'),
    rtl: fromDistinct ? Boolean(base.rtl) : Boolean(p.rtl ?? base.rtl),
    theme: base.theme,
    branding: base.branding,
    demo: scrubDemo(base.demo),
    blocks: base.blocks,
  };
}

function main() {
  const previews = JSON.parse(fs.readFileSync(previewsPath, 'utf8'));
  const layouts = previews.map((p) => {
    const distinct = DISTINCT[p.formatNumber];
    const kind = FORMAT_KIND_OVERRIDE[p.formatNumber] || p.layoutKind || 'generic';
    const base = distinct
      ? deepClone(distinct)
      : deepClone((KIND_TEMPLATES[kind] || KIND_TEMPLATES.generic)());
    return toLayoutRow(p, base, kind, Boolean(distinct));
  });

  for (const spec of EXTRA_LAYOUT_SPECS) {
    const fromCommercial = EXTRA_COMMERCIAL[spec.key];
    const fromKind = typeof KIND_TEMPLATES[spec.key] === 'function' ? KIND_TEMPLATES[spec.key]() : null;
    const base = deepClone(fromCommercial || fromKind);
    if (!base) {
      console.warn('Missing layout for extra spec', spec.code, spec.key);
      continue;
    }
    layouts.push(
      toLayoutRow(
        { code: spec.code, formatNumber: spec.formatNumber, name: spec.name, paper: 'A4', rtl: false },
        base,
        'generic',
      ),
    );
  }

  fs.writeFileSync(outJson, JSON.stringify(layouts, null, 2) + '\n', 'utf8');
  const ts =
    `import type { InvoiceFormatUiLayout } from '../types/invoiceFormatUiLayout.types';\n\n` +
    `/** Auto-generated — run: node scripts/build-invoice-format-ui-layouts.mjs */\n` +
    `export const INVOICE_FORMAT_UI_LAYOUTS: InvoiceFormatUiLayout[] = ${JSON.stringify(layouts, null, 2)} as InvoiceFormatUiLayout[];\n`;
  fs.writeFileSync(outTs, ts, 'utf8');
  console.log(`Wrote ${layouts.length} layouts →`);
  console.log(' ', path.relative(root, outJson));
  console.log(' ', path.relative(root, outTs));
}

main();
